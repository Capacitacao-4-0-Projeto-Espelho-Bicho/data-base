-- =============================================================================
-- PASSO 1: LIMPEZA DO AMBIENTE (Ordem inversa de dependência)
-- =============================================================================
DROP TABLE IF EXISTS execucao CASCADE;
DROP TABLE IF EXISTS recomendacao CASCADE;
DROP TABLE IF EXISTS atividade CASCADE;
DROP TABLE IF EXISTS nivel_competencia CASCADE;
DROP TABLE IF EXISTS historico_perfil CASCADE;
DROP TABLE IF EXISTS perfil_usuario CASCADE;
DROP TABLE IF EXISTS competencia CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;

-- =============================================================================
-- PASSO 2: TABELAS BASE (Usuário e Competências)
-- =============================================================================

-- Tabela de Usuário (Bloco 1: Identificação mínima)
CREATE TABLE usuario (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150) NOT NULL,
    email          VARCHAR(150) NOT NULL,
    data_cadastro  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,

    -- Garante que não haja dois usuários com o mesmo e-mail
    CONSTRAINT uq_usuario_email UNIQUE (email)
);

COMMENT ON TABLE usuario IS 'Cadastro base do usuário (Bloco 1 do Plano de Entregas).';

-- Tabela de Competências (As 10 Soft Skills do SENAI)
CREATE TABLE competencia (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL,
    descricao   TEXT,
    data_criado TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,

    -- Evita duplicar nomes de competências
    CONSTRAINT uq_competencia_nome UNIQUE (nome)
);

COMMENT ON TABLE competencia IS 'As 10 competências do Quadro de Soft Skills do SENAI.';

-- =============================================================================
-- PASSO 3: PERFIL E CONTEXTO (Bloco 3 + Histórico Automático)
-- =============================================================================

-- Perfil do Usuário (Contexto declarado nas 4 dimensões)
CREATE TABLE perfil_usuario (
    id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id         INT          NOT NULL,
    ambiente           VARCHAR(30)  NOT NULL,
    tempo              VARCHAR(30)  NOT NULL,
    recursos           VARCHAR(30)  NOT NULL,
    interlocutores     VARCHAR(30)  NOT NULL,
    origem_atualizacao VARCHAR(30)  NOT NULL DEFAULT 'onboarding',
    atualizado_em      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,

    -- Vínculo com o usuário (se apagar o usuário, apaga o perfil)
    CONSTRAINT fk_perfil_usuario 
        FOREIGN KEY (usuario_id) REFERENCES usuario(id) 
        ON DELETE CASCADE,

    -- Garante que cada usuário tenha apenas um perfil ativo
    CONSTRAINT uq_perfil_usuario_id UNIQUE (usuario_id),

    -- TRAVAS DE SEGURANÇA (Vocabulário controlado da Seção 1.4)
    CONSTRAINT chk_perfil_ambiente CHECK (ambiente IN ('individual', 'em_aula', 'em_equipe', 'no_trabalho')),
    CONSTRAINT chk_perfil_tempo CHECK (tempo IN ('ate_15_min', '15_a_45_min', 'mais_45_min')),
    CONSTRAINT chk_perfil_recursos CHECK (recursos IN ('nenhum', 'papel_ou_celular', 'computador')),
    CONSTRAINT chk_perfil_interlocutores CHECK (interlocutores IN ('sozinho', 'com_colega', 'com_grupo'))
);

COMMENT ON TABLE perfil_usuario IS 'Contexto de prática do usuário (Bloco 3). Representa a "Oportunidade" do modelo COM-B.';

-- Histórico do Perfil (Auditoria automática via Trigger)
CREATE TABLE historico_perfil (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     INT          NOT NULL,
    ambiente       VARCHAR(30)  NOT NULL,
    tempo          VARCHAR(30)  NOT NULL,
    recursos       VARCHAR(30)  NOT NULL,
    interlocutores VARCHAR(30)  NOT NULL,
    origem         VARCHAR(30)  NOT NULL,
    motivo         TEXT,
    data_registro  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_hist_perfil_usuario 
        FOREIGN KEY (usuario_id) REFERENCES usuario(id) 
        ON DELETE CASCADE
);

COMMENT ON TABLE historico_perfil IS 'Log automático de mudanças de contexto para auditoria e análise.';

-- Trigger e Função para salvar o histórico automaticamente antes de atualizar o perfil
CREATE OR REPLACE FUNCTION registrar_historico_perfil()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO historico_perfil (
        usuario_id, ambiente, tempo, recursos, interlocutores, origem, data_registro
    )
    VALUES (
        OLD.usuario_id, OLD.ambiente, OLD.tempo, OLD.recursos, OLD.interlocutores, 
        OLD.origem_atualizacao, CURRENT_TIMESTAMP
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_historico_perfil
BEFORE UPDATE ON perfil_usuario
FOR EACH ROW
EXECUTE FUNCTION registrar_historico_perfil();

-- =============================================================================
-- PASSO 4: AVALIAÇÃO (Bloco 2: Autoavaliação por competência)
-- =============================================================================

-- Nível da Competência (Média das notas 1 a 4)
CREATE TABLE nivel_competencia (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       INT          NOT NULL,
    competencia_id   INT          NOT NULL,
    nivel            DECIMAL(3,2) NOT NULL, -- Média calculada (ex: 2.50)
    data_avaliacao   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_nivel_usuario 
        FOREIGN KEY (usuario_id) REFERENCES usuario(id) 
        ON DELETE CASCADE,
    CONSTRAINT fk_nivel_competencia 
        FOREIGN KEY (competencia_id) REFERENCES competencia(id) 
        ON DELETE RESTRICT, -- Não deixa apagar competência se tiver avaliações

    -- Um usuário só pode ter um nível registrado por competência (o mais recente)
    CONSTRAINT uq_nivel_usuario_competencia UNIQUE (usuario_id, competencia_id),
    
    -- O nível deve estar entre 1 e 4
    CONSTRAINT chk_nivel_valor CHECK (nivel BETWEEN 1.00 AND 4.00)
);

COMMENT ON TABLE nivel_competencia IS 'Resultado da autoavaliação (Bloco 2). Define as prioridades formativas.';

-- =============================================================================
-- PASSO 5: CATÁLOGO DE ATIVIDADES
-- =============================================================================

CREATE TABLE atividade (
    id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(200) NOT NULL,
    competencia_id    INT          NOT NULL,
    dificuldade       SMALLINT     NOT NULL,
    duracao_min       INTEGER      NOT NULL,
    ambiente          VARCHAR(30)  NOT NULL,
    tempo             VARCHAR(30)  NOT NULL,
    recursos          VARCHAR(30)  NOT NULL,
    interlocutores    VARCHAR(30)  NOT NULL,
    evidencia_exigida VARCHAR(50)  NOT NULL,
    descricao         TEXT,
    data_criado       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_atividade_competencia 
        FOREIGN KEY (competencia_id) REFERENCES competencia(id) 
        ON DELETE RESTRICT,

    -- TRAVAS DE SEGURANÇA (Metadados da atividade)
    CONSTRAINT chk_atv_dificuldade CHECK (dificuldade BETWEEN 1 AND 3),
    CONSTRAINT chk_atv_duracao CHECK (duracao_min > 0),
    CONSTRAINT chk_atv_ambiente CHECK (ambiente IN ('individual', 'em_aula', 'em_equipe', 'no_trabalho')),
    CONSTRAINT chk_atv_tempo CHECK (tempo IN ('ate_15_min', '15_a_45_min', 'mais_45_min')),
    CONSTRAINT chk_atv_recursos CHECK (recursos IN ('nenhum', 'papel_ou_celular', 'computador')),
    CONSTRAINT chk_atv_interlocutores CHECK (interlocutores IN ('sozinho', 'com_colega', 'com_grupo')),
    CONSTRAINT chk_atv_evidencia CHECK (evidencia_exigida IN ('texto', 'arquivo', 'registro_conclusao'))
);

COMMENT ON TABLE atividade IS 'Catálogo de microatividades anotadas para a cadeia de seleção.';

-- =============================================================================
-- PASSO 6: RECOMENDAÇÃO E EXECUÇÃO
-- =============================================================================

CREATE TABLE recomendacao (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     INT          NOT NULL,
    atividade_id   INT          NOT NULL,
    data_gerada    DATE         NOT NULL DEFAULT CURRENT_DATE,
    regra_usada    VARCHAR(100) NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'gerada',
    motivo_recusa  TEXT,
    data_decisao   TIMESTAMP,

    CONSTRAINT fk_rec_usuario 
        FOREIGN KEY (usuario_id) REFERENCES usuario(id) 
        ON DELETE CASCADE,
    CONSTRAINT fk_rec_atividade 
        FOREIGN KEY (atividade_id) REFERENCES atividade(id) 
        ON DELETE RESTRICT,

    -- Regra de ouro: Nenhuma recomendação repetida no mesmo dia
    CONSTRAINT uq_rec_dia UNIQUE (usuario_id, atividade_id, data_gerada),

    -- Trava de status (máquina de estados)
    CONSTRAINT chk_rec_status CHECK (status IN ('gerada', 'apresentada', 'aceite', 'recusada', 'expirada'))
);

COMMENT ON TABLE recomendacao IS 'Atividade sugerida com rastreabilidade da regra aplicada.';

CREATE TABLE execucao (
    id                   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recomendacao_id      INT          NOT NULL,
    evidencia_arquivo    VARCHAR(255),
    data_envio           TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    feedback             TEXT,
    progresso_atualizado DECIMAL(5,2),

    CONSTRAINT fk_exec_recomendacao 
        FOREIGN KEY (recomendacao_id) REFERENCES recomendacao(id) 
        ON DELETE CASCADE,

    -- Regra 1 para 0..1: Cada recomendação gera no máximo UMA execução
    CONSTRAINT uq_exec_recomendacao UNIQUE (recomendacao_id),

    -- Progresso deve ser uma porcentagem válida
    CONSTRAINT chk_exec_progresso CHECK (progresso_atualizado IS NULL OR (progresso_atualizado >= 0 AND progresso_atualizado <= 100))
);

COMMENT ON TABLE execucao IS 'Evidência da atividade realizada e feedback gerado.';

-- =============================================================================
-- PASSO 7: ÍNDICES DE PERFORMANCE (Para a cadeia de seleção ser rápida)
-- =============================================================================
CREATE INDEX idx_perfil_usuario ON perfil_usuario(usuario_id);
CREATE INDEX idx_nivel_usuario ON nivel_competencia(usuario_id);
CREATE INDEX idx_atividade_competencia ON atividade(competencia_id);
CREATE INDEX idx_recomendacao_usuario ON recomendacao(usuario_id);

-- Índice composto para acelerar o Passo 2 da cadeia de seleção (Filtro por contexto)
CREATE INDEX idx_atividade_filtro_contexto 
    ON atividade(competencia_id, ambiente, tempo, recursos, interlocutores);

